import fs from 'fs';
import path from 'path';
import os from 'os';
import crypto from 'crypto';
import { CommitMessage, LoggedCommit, UserHistoryStore } from '../types/index.js';
import { MAX_HISTORY_STORED_COMMITS } from '../constants/index.js';

const DEFAULT_HISTORY_PATH = path.join(os.homedir(), '.gcai', 'history.json');

export function getHistoryPath(): string {
  return DEFAULT_HISTORY_PATH;
}

export function getHistory(filePath = DEFAULT_HISTORY_PATH): UserHistoryStore {
  try {
    if (fs.existsSync(filePath)) {
      const raw = fs.readFileSync(filePath, 'utf8');
      return JSON.parse(raw);
    }
  } catch {
    // Return clean store on read error
  }
  return { commits: [] };
}

export function saveHistory(store: UserHistoryStore, filePath = DEFAULT_HISTORY_PATH): void {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(filePath, JSON.stringify(store, null, 2), 'utf8');
}

export function logCommit(
  commit: CommitMessage,
  repoName: string,
  repoPath: string,
  filesChanged: number,
  additions: number,
  deletions: number,
  filePath = DEFAULT_HISTORY_PATH
): LoggedCommit {
  const store = getHistory(filePath);

  const logged: LoggedCommit = {
    id: crypto.randomUUID(),
    repoName,
    repoPath,
    timestamp: new Date().toISOString(),
    type: commit.type,
    scope: commit.scope,
    subject: commit.subject,
    formatted: commit.formatted,
    filesChanged,
    additions,
    deletions,
  };

  store.commits.unshift(logged);
  
  if (store.commits.length > MAX_HISTORY_STORED_COMMITS) {
    store.commits = store.commits.slice(0, MAX_HISTORY_STORED_COMMITS);
  }

  saveHistory(store, filePath);
  return logged;
}

export function getCommitStats(commits: LoggedCommit[]) {
  const byType: Record<string, number> = {};
  let totalAdditions = 0;
  let totalDeletions = 0;
  let totalFiles = 0;

  for (const c of commits) {
    byType[c.type] = (byType[c.type] || 0) + 1;
    totalAdditions += c.additions;
    totalDeletions += c.deletions;
    totalFiles += c.filesChanged;
  }

  return {
    totalCommits: commits.length,
    byType,
    totalAdditions,
    totalDeletions,
    totalFiles,
  };
}

export function exportChangelog(commits: LoggedCommit[]): string {
  const features = commits.filter((c) => c.type === 'feat');
  const fixes = commits.filter((c) => c.type === 'fix');
  const refactors = commits.filter((c) => c.type === 'refactor');
  const chores = commits.filter((c) => c.type === 'chore' || c.type === 'build' || c.type === 'ci');
  const others = commits.filter(
    (c) => !['feat', 'fix', 'refactor', 'chore', 'build', 'ci'].includes(c.type)
  );

  let md = `# Changelog\n\nGenerated by **conventionalize** on ${new Date().toLocaleDateString()}\n\n`;

  if (features.length > 0) {
    md += `### Features\n`;
    for (const f of features) {
      const scopeStr = f.scope ? `**${f.scope}**: ` : '';
      md += `- ${scopeStr}${f.subject} (*${f.repoName}*)\n`;
    }
    md += '\n';
  }

  if (fixes.length > 0) {
    md += `### Bug Fixes\n`;
    for (const fix of fixes) {
      const scopeStr = fix.scope ? `**${fix.scope}**: ` : '';
      md += `- ${scopeStr}${fix.subject} (*${fix.repoName}*)\n`;
    }
    md += '\n';
  }

  if (refactors.length > 0) {
    md += `### Refactoring & Improvements\n`;
    for (const r of refactors) {
      const scopeStr = r.scope ? `**${r.scope}**: ` : '';
      md += `- ${scopeStr}${r.subject}\n`;
    }
    md += '\n';
  }

  if (chores.length > 0) {
    md += `### Maintenance & Build\n`;
    for (const c of chores) {
      const scopeStr = c.scope ? `**${c.scope}**: ` : '';
      md += `- ${scopeStr}${c.subject}\n`;
    }
    md += '\n';
  }

  if (others.length > 0) {
    md += `### Other Changes\n`;
    for (const o of others) {
      const scopeStr = o.scope ? `**${o.scope}**: ` : '';
      md += `- ${scopeStr}${o.subject}\n`;
    }
    md += '\n';
  }

  return md;
}
